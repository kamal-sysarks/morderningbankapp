CREATE TABLE IF NOT EXISTS EMPLOYEES (
    EMPLOYEE_ID    BIGINT PRIMARY KEY AUTO_INCREMENT,
    USERNAME       VARCHAR(50)   NOT NULL UNIQUE,
    PASSWORD       VARCHAR(100)  NOT NULL,
    EMPLOYEE_NAME  VARCHAR(100)  NOT NULL,
    STATUS         VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE'
);

CREATE TABLE IF NOT EXISTS CUSTOMERS (
    CUSTOMER_ID    BIGINT PRIMARY KEY AUTO_INCREMENT,
    CUSTOMER_NAME  VARCHAR(100)  NOT NULL,
    EMAIL          VARCHAR(100),
    PHONE          VARCHAR(30),
    ADDRESS        VARCHAR(250),
    CREATED_DATE   VARCHAR(30)   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ACCOUNTS (
    ACCOUNT_ID      BIGINT PRIMARY KEY AUTO_INCREMENT,
    ACCOUNT_NUMBER  VARCHAR(20)   NOT NULL UNIQUE,
    CUSTOMER_ID     BIGINT        NOT NULL REFERENCES CUSTOMERS(CUSTOMER_ID),
    ACCOUNT_TYPE    VARCHAR(20)   NOT NULL,
    BALANCE         DECIMAL(15,2) NOT NULL DEFAULT 0,
    STATUS          VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
    CREATED_DATE    VARCHAR(30)   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS TRANSACTIONS (
    TRANSACTION_ID    BIGINT PRIMARY KEY AUTO_INCREMENT,
    ACCOUNT_NUMBER    VARCHAR(20)   NOT NULL,
    TRANSACTION_TYPE  VARCHAR(20)   NOT NULL,
    AMOUNT            DECIMAL(15,2) NOT NULL,
    DESCRIPTION       VARCHAR(250),
    TRANSACTION_DATE  VARCHAR(30)   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REFERENCE_NUMBER  VARCHAR(30)   NOT NULL
);

CREATE TABLE IF NOT EXISTS REFERENCE_SEQUENCE (
    REF_ID BIGINT PRIMARY KEY AUTO_INCREMENT
);
